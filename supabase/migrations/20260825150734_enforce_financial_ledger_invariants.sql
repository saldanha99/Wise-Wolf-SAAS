-- paid_at passa a significar a data efetiva usada pelo caixa. CONFIRMED nao
-- preenche mais este campo. Em RECEIVED, creditDate vence todas as estimativas.
create or replace function public.set_student_payment_paid_at()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  v_cash_now boolean;
  v_cash_before boolean;
begin
  v_cash_now := new.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA');
  v_cash_before := tg_op = 'UPDATE'
                   and old.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA');

  if new.status = 'CONFIRMED' then
    new.paid_at := null;
  elsif v_cash_now then
    if new.credited_at is not null then
      new.paid_at := new.credited_at;
    elsif new.paid_at is null
          or not v_cash_before
          or (
            tg_op = 'UPDATE'
            and (
              old.payment_date is distinct from new.payment_date
              or old.due_date is distinct from new.due_date
            )
          ) then
      new.paid_at := coalesce(
        new.payment_date + interval '12 hours',
        new.due_date + interval '12 hours',
        now()
      );
    end if;
  end if;

  return new;
end;
$function$;

alter function public.set_student_payment_paid_at() owner to postgres;

drop trigger if exists trg_student_payment_paid_at on public.student_payments;
create trigger trg_student_payment_paid_at
  before insert or update of status, credited_at, paid_at, payment_date, due_date
  on public.student_payments
  for each row execute function public.set_student_payment_paid_at();

