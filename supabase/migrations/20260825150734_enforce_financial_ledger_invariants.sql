-- O rateio/notificacao acompanha dinheiro efetivamente disponibilizado. A
-- confirmacao ainda pode ser estornada antes do credito e nao pode disparar
-- uma automacao financeira antecipada.
create or replace function public.notify_payment_split()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_service_key text;
  v_request_id bigint;
begin
  if new.status not in ('RECEIVED', 'RECEIVED_IN_CASH')
     or coalesce(new.value, 0) <= 0
  then
    return new;
  end if;

  if tg_op = 'UPDATE' and old.status is not distinct from new.status then
    return new;
  end if;

  if not exists (
    select 1
      from public.payment_split_settings as setting
     where setting.tenant_id = new.tenant_id
       and setting.is_active
  ) then
    return new;
  end if;

  select secret.decrypted_secret
    into v_service_key
    from vault.decrypted_secrets as secret
   where secret.name = 'wisewolf_service_role_key'
   limit 1;
  if nullif(v_service_key, '') is null then
    raise warning 'notify_payment_split: service key ausente';
    return new;
  end if;

  select net.http_post(
    url := 'http://kong:8000/functions/v1/payment-split-notify',
    headers := pg_catalog.jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || v_service_key
    ),
    body := pg_catalog.jsonb_build_object('payment_id', new.id),
    timeout_milliseconds := 20000
  ) into v_request_id;

  return new;
exception when others then
  raise warning 'notify_payment_split falhou (pagamento preservado): %', sqlerrm;
  return new;
end;
$function$;

