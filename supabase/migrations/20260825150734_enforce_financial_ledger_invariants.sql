-- Invariantes do caixa e da conciliacao Asaas.
--
-- Esta migration consolida uma unica regra para qualquer escritor
-- (webhook, tela, RPC ou reconciliador):
--   * CONFIRMED nao e caixa;
--   * RECEIVED / RECEIVED_IN_CASH sao caixa;
--   * NAO_RECEITA continua sendo dinheiro que entrou, mas em categoria
--     nao operacional;
--   * existe no maximo uma ENTRADA bruta por student_payment;
--   * cada estorno concluido e uma SAIDA separada, identificada pelo evento;
--   * credited_at, quando informado pelo Asaas, e a data efetiva do caixa;
--   * flags nunca sao fonte da verdade: sao derivadas da existencia da linha.

