insert into public.reconciliation_issues (
  tenant_id, kind, student_payment_id, details
)
select
  coalesce(sp.tenant_id, 'master'),
  'HISTORICAL_REFUND_EVENT_CONTEXT_MISSING',
  sp.id,
  jsonb_build_object(
    'status', sp.status,
    'valor_bruto', sp.value,
    'valor_estornado_acumulado', sp.refunded_amount,
    'soma_saidas_com_evento', coalesce(refunds.total, 0),
    'last_provider_event_id', sp.last_provider_event_id,
    'last_provider_event_at', sp.last_provider_event_at,
    'data_sintetizada', false,
    'registrado_em', now()
  )
from public.student_payments sp
left join lateral (
  select sum(ft.amount) as total
    from public.financial_transactions ft
   where ft.refund_student_payment_id = sp.id
) refunds on true
where (
    sp.status = 'REFUNDED'
    or coalesce(sp.refunded_amount, 0) > coalesce(refunds.total, 0)
  )
  and (
    sp.credited_at is not null
    or sp.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA')
    or exists (
      select 1
        from public.financial_transactions receipt
       where receipt.student_payment_id = sp.id
    )
  )
  and not exists (
    select 1
      from public.reconciliation_issues ri
     where ri.student_payment_id = sp.id
       and ri.kind = 'HISTORICAL_REFUND_EVENT_CONTEXT_MISSING'
       and not coalesce(ri.resolved, false)
  );

-- -------------------------------------------------------------------------
-- 7. Reconciliacao transacional, paginavel e baseada em NOT EXISTS
-- -------------------------------------------------------------------------

create or replace function public.reconcile_student_payment_ledger(
  p_limit integer default 100,
  p_after_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_payment record;
  v_limit integer;
  v_processed integer := 0;
  v_inserted integer := 0;
  v_delta integer := 0;
  v_flags_corrected integer := 0;
  v_last_id uuid := null;
  v_has_more boolean := false;
  v_lock_acquired boolean;
  v_gross_amount numeric;
begin
  v_limit := greatest(1, least(coalesce(p_limit, 100), 1000));

  select pg_try_advisory_xact_lock(
    hashtextextended('wise-wolf:reconcile-student-payment-ledger', 0)
  ) into v_lock_acquired;

  if not v_lock_acquired then
    return jsonb_build_object(
      'busy', true,
      'processed', 0,
      'inserted', 0,
      'flags_corrected', 0,
      'next_after_id', null,
      'has_more', false
    );
  end if;

  for v_payment in
    select sp.*
      from public.student_payments sp
     where (
         sp.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA')
         or (sp.status = 'REFUNDED' and sp.credited_at is not null)
       )
       and sp.tenant_id is not null
       and coalesce(sp.value, 0) > 0
       and (p_after_id is null or sp.id > p_after_id)
       and not exists (
         select 1
           from public.financial_transactions ft
          where ft.student_payment_id = sp.id
       )
     order by sp.id
     limit v_limit
     for update of sp
  loop
    v_processed := v_processed + 1;
    v_last_id := v_payment.id;
    v_gross_amount := round(coalesce(v_payment.value, 0), 2);

    insert into public.financial_transactions (
      tenant_id,
      type,
      category,
      amount,
      amount_cents,
      student_payment_id,
      reference_id,
      occurred_at,
      description,
      created_at
    ) values (
      v_payment.tenant_id,
      'ENTRADA',
      case
        when v_payment.status = 'NAO_RECEITA' then 'aporte_ou_movimentacao'
        else 'MENSALIDADE'
      end,
      v_gross_amount,
      round(v_gross_amount * 100)::integer,
      v_payment.id,
      v_payment.student_id,
      coalesce(
        v_payment.credited_at,
        v_payment.paid_at,
        v_payment.payment_date + interval '12 hours',
        v_payment.due_date + interval '12 hours',
        now()
      ),
      case
        when v_payment.status = 'NAO_RECEITA' then 'Movimentacao nao operacional (reconciliacao)'
        else 'Mensalidade (reconciliacao)'
      end,
      now()
    )
    on conflict (student_payment_id) where student_payment_id is not null
    do nothing;

    get diagnostics v_delta = row_count;
    v_inserted := v_inserted + v_delta;
  end loop;

  with ledger_state as (
    select
      sp.id,
      exists (
        select 1
          from public.financial_transactions ft
         where ft.student_payment_id = sp.id
      ) as has_ledger
    from public.student_payments sp
  ), corrected as (
    update public.student_payments sp
       set ledger_entry_created = ls.has_ledger
      from ledger_state ls
     where ls.id = sp.id
       and sp.ledger_entry_created is distinct from ls.has_ledger
    returning 1
  )
  select count(*) into v_flags_corrected from corrected;

  if v_last_id is not null then
    select exists (
      select 1
        from public.student_payments sp
       where (
           sp.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA')
           or (sp.status = 'REFUNDED' and sp.credited_at is not null)
         )
         and sp.tenant_id is not null
         and coalesce(sp.value, 0) > 0
         and sp.id > v_last_id
         and not exists (
           select 1
             from public.financial_transactions ft
            where ft.student_payment_id = sp.id
         )
    ) into v_has_more;
  end if;

  return jsonb_build_object(
    'busy', false,
    'processed', v_processed,
    'inserted', v_inserted,
    'flags_corrected', v_flags_corrected,
