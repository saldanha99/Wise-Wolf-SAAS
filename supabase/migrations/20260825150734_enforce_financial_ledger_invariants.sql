-- As demais funcoes sao extensas e ja possuem regras de permissao, custo e
-- rateio auditadas. A substituicao assertiva abaixo troca somente a definicao
-- de receita realizada. Cada quantidade e verificada antes do CREATE OR REPLACE;
-- qualquer drift futuro faz a migration abortar em vez de alterar SQL errado.
do $net_revenue_reports$
declare
  patch record;
  v_definition text;
  v_old_occurrences integer;
  v_new_occurrences integer;
begin
  for patch in
    select *
      from (values
        (
          'public.dre_gerencial(text,text)',
          $old$SELECT COALESCE(sum(value),0) INTO v_receita$old$,
          $new$SELECT COALESCE(sum(greatest(round(coalesce(value, 0) - coalesce(refunded_amount, 0), 2), 0)),0) INTO v_receita$new$,
          1
        ),
        (
          'public.dre_gerencial(text,text)',
          $old$to_char(COALESCE(paid_at, payment_date, due_date),'YYYY-MM')$old$,
          $new$to_char(COALESCE(credited_at, paid_at, payment_date, due_date),'YYYY-MM')$new$,
          1
        ),
        (
          'public.dre_gerencial(text,text)',
          $old$WHERE ft.tenant_id = v_tenant AND ft.type = 'SAIDA'
      AND to_char(COALESCE(ft.occurred_at, ft.created_at),'YYYY-MM') = v_month$old$,
          $new$WHERE ft.tenant_id = v_tenant AND ft.type = 'SAIDA'
      AND ft.category IS DISTINCT FROM 'teacher_payout'
      AND ft.refund_student_payment_id IS NULL
      AND to_char(COALESCE(ft.occurred_at, ft.created_at),'YYYY-MM') = v_month$new$,
          1
        ),
        (
          'public.director_teacher_margin(text)',
          $old$sum(COALESCE(sp.value, sp.amount_cents / 100.0))$old$,
          $new$sum(greatest(round(coalesce(sp.value, 0) - coalesce(sp.refunded_amount, 0), 2), 0))$new$,
          2
        ),
        (
          'public.director_teacher_margin(text)',
          $old$sp.status IN ('RECEIVED','CONFIRMED','PAID','RECEIVED_IN_CASH')$old$,
          $new$sp.status IN ('RECEIVED','RECEIVED_IN_CASH')$new$,
          2
        ),
        (
          'public.director_teacher_margin(text)',
          $old$COALESCE(sp.paid_at::date, sp.payment_date, sp.due_date)$old$,
          $new$COALESCE(sp.credited_at::date, sp.paid_at::date, sp.payment_date, sp.due_date)$new$,
          2
        ),
        (
          'public.balancete_professores(text,text)',
          $old$sum(sp.value)$old$,
          $new$sum(greatest(round(coalesce(sp.value, 0) - coalesce(sp.refunded_amount, 0), 2), 0))$new$,
          4
        ),
        (
          'public.balancete_professores(text,text)',
          $old$COALESCE(sp.paid_at, sp.payment_date, sp.due_date)$old$,
          $new$COALESCE(sp.credited_at, sp.paid_at, sp.payment_date, sp.due_date)$new$,
          4
        ),
        (
          'public.balancete_receita_sem_aula(text,text)',
          $old$sum(sp.value)$old$,
          $new$sum(greatest(round(coalesce(sp.value, 0) - coalesce(sp.refunded_amount, 0), 2), 0))$new$,
          1
        ),
        (
          'public.balancete_receita_sem_aula(text,text)',
          $old$COALESCE(sp.paid_at, sp.payment_date, sp.due_date)$old$,
          $new$COALESCE(sp.credited_at, sp.paid_at, sp.payment_date, sp.due_date)$new$,
          1
        ),
        (
          'public.financial_reconciliation(text)',
          $old$coalesce((select sum(sp.value) from public.student_payments sp
                     where sp.student_id = p.id
                       and sp.status in ('RECEIVED', 'RECEIVED_IN_CASH')), 0) as recebido$old$,
          $new$coalesce((select sum(greatest(round(coalesce(sp.value, 0) - coalesce(sp.refunded_amount, 0), 2), 0)) from public.student_payments sp
                     where sp.student_id = p.id
                       and sp.status in ('RECEIVED', 'RECEIVED_IN_CASH')), 0) as recebido$new$,
          1
        )
      ) as replacements(signature, old_sql, new_sql, expected_occurrences)
  loop
    if to_regprocedure(patch.signature) is null then
      raise exception 'required financial report function is missing: %', patch.signature;
    end if;

    select pg_get_functiondef(to_regprocedure(patch.signature))
      into v_definition;
    v_old_occurrences := (
      length(v_definition) - length(replace(v_definition, patch.old_sql, ''))
    ) / length(patch.old_sql);
    v_new_occurrences := (
      length(v_definition) - length(replace(v_definition, patch.new_sql, ''))
    ) / length(patch.new_sql);

    if v_old_occurrences = patch.expected_occurrences
       and v_new_occurrences = 0 then
      execute replace(v_definition, patch.old_sql, patch.new_sql);
    elsif v_old_occurrences = 0
          and v_new_occurrences = patch.expected_occurrences then
      null;
    else
      raise exception
        'financial report drift for %: expected OLD=%/NEW=0 or OLD=0/NEW=%; found OLD=%/NEW=%',
        patch.signature,
        patch.expected_occurrences,
        patch.expected_occurrences,
        v_old_occurrences,
        v_new_occurrences;
    end if;

    select pg_get_functiondef(to_regprocedure(patch.signature))
      into v_definition;
    v_old_occurrences := (
      length(v_definition) - length(replace(v_definition, patch.old_sql, ''))
    ) / length(patch.old_sql);
    v_new_occurrences := (
      length(v_definition) - length(replace(v_definition, patch.new_sql, ''))
    ) / length(patch.new_sql);

    if v_old_occurrences <> 0
       or v_new_occurrences <> patch.expected_occurrences then
      raise exception
        'financial report patch postcondition failed for %: OLD=%/NEW=%',
        patch.signature,
        v_old_occurrences,
        v_new_occurrences;
    end if;
  end loop;
end
