do $postconditions$
begin
  if exists (
    select 1
      from public.financial_transactions ft
     where ft.amount_cents <> round(ft.amount * 100)::integer
  ) then
    raise exception 'financial_transactions amount equivalence failed';
  end if;

  if exists (
    select 1
      from public.student_payments sp
     where not (
       (sp.value is null and sp.amount_cents is null)
       or (
         sp.value is not null
         and sp.amount_cents is not null
         and sp.amount_cents = round(sp.value * 100)::integer
       )
     )
  ) then
    raise exception 'student_payments amount equivalence failed';
  end if;

  if exists (
    select 1
      from public.student_payments sp
      join public.financial_transactions ft on ft.student_payment_id = sp.id
     where sp.status <> 'REFUNDED'
       and (
         sp.status not in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA')
         or sp.tenant_id is null
         or coalesce(sp.value, 0) <= 0
       )
  ) then
    raise exception 'non-canonical student payment still has a ledger entry';
  end if;

  if exists (
    select 1
      from public.student_payments sp
     where (
         sp.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA')
         or (sp.status = 'REFUNDED' and sp.credited_at is not null)
       )
       and sp.tenant_id is not null
       and coalesce(sp.value, 0) > 0
       and not exists (
         select 1
           from public.financial_transactions ft
          where ft.student_payment_id = sp.id
       )
  ) then
    raise exception 'cash student payment is missing its ledger entry';
  end if;

  if exists (
    select 1
      from public.student_payments sp
      join public.financial_transactions ft on ft.student_payment_id = sp.id
     where (
         sp.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA')
         or (sp.status = 'REFUNDED' and sp.credited_at is not null)
       )
       and sp.tenant_id is not null
       and coalesce(sp.value, 0) > 0
       and (
         ft.tenant_id is distinct from sp.tenant_id
         or ft.type is distinct from 'ENTRADA'
         or ft.category is distinct from case
           when sp.status = 'NAO_RECEITA' then 'aporte_ou_movimentacao'
           else 'MENSALIDADE'
         end
         or ft.amount is distinct from round(sp.value, 2)
         or ft.amount_cents is distinct from round(sp.value * 100)::integer
         or ft.reference_id is distinct from sp.student_id
         or ft.occurred_at is distinct from coalesce(
           sp.credited_at,
           sp.paid_at,
           sp.payment_date + interval '12 hours',
           sp.due_date + interval '12 hours',
           ft.occurred_at
         )
       )
  ) then
    raise exception 'student payment ledger fields diverge from canonical payment data';
  end if;

  if exists (
    select 1
      from public.financial_transactions ft
     where ft.refund_student_payment_id is not null
       and (
         ft.student_payment_id is not null
         or ft.type <> 'SAIDA'
         or ft.amount <= 0
         or ft.category not in (
           'ESTORNO_MENSALIDADE',
           'estorno_aporte_ou_movimentacao'
         )
         or ft.provider_event_id is null
         or length(trim(ft.provider_event_id)) not between 1 and 240
       )
  ) then
    raise exception 'refund ledger row has a non-canonical shape';
  end if;

  if exists (
    select 1
      from public.financial_transactions ft
      join public.student_payments sp on sp.id = ft.refund_student_payment_id
     where ft.category is distinct from case
       when sp.status = 'NAO_RECEITA'
         then 'estorno_aporte_ou_movimentacao'
       else 'ESTORNO_MENSALIDADE'
     end
  ) then
    raise exception 'refund ledger category diverges from payment classification';
  end if;

  if exists (
    select 1
      from public.student_payments sp
      join lateral (
        select coalesce(sum(ft.amount), 0) as total
          from public.financial_transactions ft
         where ft.refund_student_payment_id = sp.id
      ) refunds on true
     where refunds.total > coalesce(sp.refunded_amount, 0)
  ) then
    raise exception 'refund event ledger exceeds the cumulative provider refund';
  end if;

  if exists (
    select 1
      from public.student_payments sp
     where sp.status in ('RECEIVED', 'RECEIVED_IN_CASH', 'NAO_RECEITA')
       and sp.credited_at is not null
       and sp.paid_at is distinct from sp.credited_at
  ) then
    raise exception 'credited_at is not reflected in paid_at';
  end if;

  if not exists (
    select 1
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      join pg_index i on i.indexrelid = c.oid
     where n.nspname = 'public'
       and c.relname = 'uq_financial_transactions_student_payment'
       and i.indisunique
       and i.indrelid = 'public.financial_transactions'::regclass
       and i.indnkeyatts = 1
       and i.indkey[0] = (
         select a.attnum
           from pg_attribute a
          where a.attrelid = 'public.financial_transactions'::regclass
            and a.attname = 'student_payment_id'
            and not a.attisdropped
       )
       and pg_get_expr(i.indpred, i.indrelid) = '(student_payment_id IS NOT NULL)'
  ) then
    raise exception 'student payment ledger unique index definition diverged';
  end if;

  if not exists (
    select 1
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      join pg_index i on i.indexrelid = c.oid
     where n.nspname = 'public'
       and c.relname = 'uq_financial_transactions_refund_event'
       and i.indisunique
       and i.indrelid = 'public.financial_transactions'::regclass
       and i.indnkeyatts = 1
       and i.indkey[0] = (
         select a.attnum
           from pg_attribute a
          where a.attrelid = 'public.financial_transactions'::regclass
            and a.attname = 'provider_event_id'
            and not a.attisdropped
       )
       and pg_get_expr(i.indpred, i.indrelid) =
         '((refund_student_payment_id IS NOT NULL) AND (provider_event_id IS NOT NULL))'
  ) then
    raise exception 'refund provider event unique index definition diverged';
  end if;

  if exists (
    select 1
      from public.student_payments sp
     where sp.ledger_entry_created is distinct from exists (
       select 1
         from public.financial_transactions ft
        where ft.student_payment_id = sp.id
     )
  ) then
    raise exception 'ledger_entry_created diverges from ledger existence';
  end if;
