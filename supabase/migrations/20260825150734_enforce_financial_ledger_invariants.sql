create or replace function public.sync_student_payment_amounts()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  v_value_changed boolean;
  v_cents_changed boolean;
begin
  if tg_op = 'INSERT' then
    if new.value is null and new.amount_cents is not null then
      new.value := new.amount_cents / 100.0;
    elsif new.value is not null and new.amount_cents is null then
      new.amount_cents := round(new.value * 100)::integer;
    elsif new.value is not null
          and new.amount_cents is not null
          and new.amount_cents <> round(new.value * 100)::integer then
      raise exception using
        errcode = '23514',
        message = 'student_payment_amount_mismatch';
    end if;
  else
    v_value_changed := new.value is distinct from old.value;
    v_cents_changed := new.amount_cents is distinct from old.amount_cents;

    if v_value_changed and not v_cents_changed then
      new.amount_cents := case
        when new.value is null then null
        else round(new.value * 100)::integer
      end;
    elsif v_cents_changed and not v_value_changed then
      new.value := case
        when new.amount_cents is null then null
        else new.amount_cents / 100.0
      end;
    elsif v_value_changed and v_cents_changed
          and not (
            new.value is null and new.amount_cents is null
          )
          and (
            new.value is null
            or new.amount_cents is null
            or new.amount_cents <> round(new.value * 100)::integer
          ) then
      raise exception using
        errcode = '23514',
        message = 'student_payment_amount_mismatch';
    end if;
  end if;

  return new;
end;
$function$;

